def decode_mips_inventory(code: bytes, base: int, limit: int = 256) -> list[dict]:
    """Lightweight MIPS word scan — inventory only (not full recomp)."""
    ops = []
    n = min(len(code) // 4, limit)
    for i in range(n):
        w = int.from_bytes(code[i * 4 : i * 4 + 4], "little")
        addr = base + i * 4
        op = (w >> 26) & 0x3F
        fn = w & 0x3F
        kind = "other"
        if w == 0:
            kind = "nop"
        elif op == 0 and fn == 0x08:
            kind = "jr"
        elif op == 0 and fn == 0x09:
            kind = "jalr"
        elif op == 0x02:
            kind = "j"
        elif op == 0x03:
            kind = "jal"
        elif op == 0x09:
            kind = "addiu"
        elif op == 0x0F:
            kind = "lui"
        elif op == 0x0C:
            kind = "syscall"
        ops.append({"addr": hex(addr), "word": hex(w), "kind": kind})
    return ops


def emit_gpu_translate_hxx() -> str:
    lines = [
        "// AUTO-GENERATED by machine_port.py — GP0 → SRL (table-driven)",
        "#pragma once",
        "#include <srl.hpp>",
        "#include <cstdint>",
        "",
        "namespace PsxSaturnBridge {",
        "namespace Gpu {",
        "",
        "inline void TranslateGp0(uint8_t cmd) {",
        "    switch (cmd) {",
    ]
    for cmd, (name, body) in sorted(GP0_TABLE.items()):
        lines.append(f"    case 0x{cmd:02X}: /* {name} */ {body} break;")
    lines += [
        "    default: /* unknown GP0 — machine no-op */ break;",
        "    }",
        "}",
        "",
        "} // namespace Gpu",
        "} // namespace PsxSaturnBridge",
        "",
    ]
    return "\n".join(lines)


def emit_machine_main(exe_meta: dict, symbols: list[str]) -> str:
    sym_c = "\n".join(f"//   - {s}" for s in symbols)
    return f"""\
// AUTO-GENERATED by machine_port.py — caminho máquina (sem humano)
#include <srl.hpp>
#include "psx_pad_map.hpp"
#include "gpu_translate.hpp"

using namespace SRL::Types;
using namespace PsxSaturnBridge;

// Provenance (machine receipt)
// exe: {exe_meta.get('path')}
// pc:  {exe_meta.get('pc_hex')}
// text:{exe_meta.get('text_addr_hex')} size={exe_meta.get('text_size')}
// sha: {exe_meta.get('code_sha256')}
{sym_c}

static void MachineBootBanner()
{{
    SRL::Debug::Print(1, 1, "machine_port: autonomous");
    SRL::Debug::Print(1, 2, "PS1->SRL driver (no human)");
}}

static void MachineTick(SRL::Input::Digital& pad)
{{
    // Input: YAML→PadMap (máquina)
    if (pad.IsConnected() && PadMap::Start(pad))
        SRL::Debug::Print(1, 4, "pad Start");

    // GPU: tabela GP0 (máquina) — alimentar com stream real no próximo incremento
    Gpu::TranslateGp0(0x02);

    // CPU: inventário MIPS no receipt; tradução ISA → SH-2 via base-recomp encode (offline)
}}

int main()
{{
    SRL::Core::Initialize(HighColor::Colors::Black);
    MachineBootBanner();
    SRL::Input::Digital pad(0);

    while (1)
    {{
        MachineTick(pad);
        SRL::Core::Synchronize();
    }}
    return 0;
}}
"""


