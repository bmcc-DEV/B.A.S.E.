def try_base_recomp_encode(out_dir: Path) -> dict:
    """Call base CLI if built — SH-2 encode smoke (máquina)."""
    repo = ROOT.parents[1]
    base = repo / "target" / "debug" / "base"
    if not base.is_file():
        return {"invoked": False, "reason": "base binary missing"}
    enc_out = out_dir / "recomp_encode"
    enc_out.mkdir(exist_ok=True)
    # nop; ret style isn't MIPS — use known hex that encode accepts for sh2 via SIR path
    # machine records attempt; failure is OK (subset)
    try:
        r = subprocess.run(
            [
                str(base),
                "recomp",
                "encode",
                "--hex",
                "B80100000083C002C3",
                "--target",
                "sh2",
                "-o",
                str(enc_out),
            ],
            capture_output=True,
            text=True,
            timeout=120,
        )
        return {
            "invoked": True,
            "returncode": r.returncode,
            "stdout_tail": (r.stdout or "")[-500:],
            "stderr_tail": (r.stderr or "")[-500:],
            "out": str(enc_out),
        }
    except Exception as e:  # noqa: BLE001
        return {"invoked": True, "error": str(e)}


def machine_port(exe_path: Path, out_root: Path, name: str) -> dict:
    data = load_map(ROOT / "mapping" / "psx_to_srl.yaml")
    symbols = collect_srl_symbols(data)
    exe = parse_psx_exe(exe_path)
    meta = exe.to_dict()
    mips = decode_mips_inventory(exe.code, exe.text_addr)

    proj = out_root / name
    if proj.exists():
        shutil.rmtree(proj)
    src = proj / "src"
    src.mkdir(parents=True)

    (src / "psx_pad_map.hpp").write_text(emit_pad_hpp(data), encoding="utf-8")
    (src / "gpu_translate.hpp").write_text(emit_gpu_translate_hxx(), encoding="utf-8")
    (src / "main.cxx").write_text(emit_machine_main(meta, symbols), encoding="utf-8")
    (proj / "makefile").write_text(emit_makefile(srl_root(), name), encoding="utf-8")

    inventory = {
        "exe": meta,
        "mips_scan": {
            "words_scanned": len(mips),
            "kinds": _count_kinds(mips),
            "sample": mips[:32],
        },
        "gp0_table_coverage": sorted(f"0x{k:02X}" for k in GP0_TABLE),
        "srl_symbols": symbols,
        "subsystems": [
            {"id": s["id"], "strategy": s.get("strategy"), "machine_owned": True}
            for s in data.get("subsystems") or []
        ],
    }
    (proj / "inventory.json").write_text(json.dumps(inventory, indent=2) + "\n", encoding="utf-8")

    recomp = try_base_recomp_encode(proj)

    receipt = {
        "driver": "machine_port",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "human_required": False,
        "machine_emits_project": True,
        "machine_closed_loop": True,
        "game_fidelity_complete": False,
        "auto_ports_games": False,
        "runs_on_saturn": False,
        "project": str(proj),
        "exe": meta.get("path"),
        "code_sha256": meta.get("code_sha256"),
        "recomp_encode": recomp,
        "next_machine_increments": [
            "expand GP0_TABLE bodies to real VDP1/Scene2D calls",
            "MIPS→SIR→SH-2 lift for leaf functions (base-recomp)",
            "ISO walker → CD file list → SRL::Cd stubs",
            "GTE op table → SRL::Math",
        ],
    }
    (proj / "MACHINE_RECEIPT.json").write_text(json.dumps(receipt, indent=2) + "\n", encoding="utf-8")

    # Also mirror pad emit into shared out/generated for bridge compat
    gen = ROOT / "out" / "generated"
    gen.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src / "psx_pad_map.hpp", gen / "psx_pad_map.hpp")

    return receipt


def _count_kinds(mips: list[dict]) -> dict:
    from collections import Counter

    return dict(Counter(x["kind"] for x in mips))


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--exe",
        type=Path,
        default=None,
        help="PS-X EXE path (default: generate fixtures/minimal.exe)",
    )
    ap.add_argument("-o", "--output", type=Path, default=ROOT / "out" / "machine_port")
    ap.add_argument("--name", default="MachinePort")
    args = ap.parse_args()

    if args.exe is None:
        fix = ROOT / "fixtures" / "minimal.exe"
        write_minimal_fixture(fix)
        exe = fix
        print(f"fixture → {fix}")
    else:
        exe = args.exe

    receipt = machine_port(exe, args.output, args.name)
    print(json.dumps({k: receipt[k] for k in (
        "machine_closed_loop",
        "human_required",
        "game_fidelity_complete",
        "project",
        "code_sha256",
    )}, indent=2))
    print(f"OK machine_port → {receipt['project']}")


if __name__ == "__main__":
    main()
